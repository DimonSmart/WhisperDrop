using System;
using System.Collections.Generic;
using System.IO;
using System.Net.Http;
using System.Net.Sockets;
using System.Reflection;
using System.Text.Json;
using System.Threading;
using WhisperDrop.Settings;

namespace WhisperDrop.State;

// AI diagnostics contain operational metadata only. Never pass transcript data,
// prompts, model responses, correction instructions, or credentials to this type.
internal sealed class TranscriptEnhancementDiagnostics : ITranscriptEnhancementDiagnostics, IDisposable
{
    private readonly object writeLock = new();
    private readonly AsyncLocal<string?> currentOperationId = new();
    private readonly StreamWriter? writer;

    internal string? FilePath { get; }

    public TranscriptEnhancementDiagnostics(IApplicationPaths applicationPaths)
    {
        try
        {
            var folder = Path.GetDirectoryName(applicationPaths.SettingsFilePath)!;
            Directory.CreateDirectory(folder);
            FilePath = Path.Combine(folder, "ai-post-processing-debug.log");
            writer = new StreamWriter(FilePath, append: true) { AutoFlush = true };
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            Console.Error.WriteLine(
                $"[WhisperDrop.AI] Could not create AI diagnostic file: {exception.GetType().Name}");
        }
    }

    public IDisposable BeginOperation(string operationId)
    {
        var previousOperationId = currentOperationId.Value;
        currentOperationId.Value = operationId;
        return new OperationScope(() => currentOperationId.Value = previousOperationId);
    }

    public void Write(string message)
    {
        var line = $"[WhisperDrop.AI] {DateTimeOffset.Now:O} operation={currentOperationId.Value ?? "unscoped"} {message}";
        Console.Error.WriteLine(line);
        try
        {
            lock (writeLock)
            {
                writer?.WriteLine(line);
            }
        }
        catch (Exception exception) when (exception is IOException or ObjectDisposedException)
        {
            Console.Error.WriteLine(
                $"[WhisperDrop.AI] Could not write diagnostic file: {exception.GetType().Name}");
        }
    }

    public void WriteException(string phase, Exception exception)
    {
        var summaries = new List<string>();
        var visited = new HashSet<Exception>();
        for (var current = exception; current is not null && visited.Add(current) && summaries.Count < 8;
             current = current.InnerException!)
        {
            summaries.Add(SummarizeException(current));
        }

        Write($"exception phase={phase} chain=[{string.Join(" -> ", summaries)}]");
    }

    private static string SummarizeException(Exception exception)
    {
        var type = exception.GetType().FullName ?? exception.GetType().Name;
        var details = new List<string> { $"type={type}", $"hresult=0x{exception.HResult:X8}" };

        // These messages are generated by our own fixed validation errors, so
        // they identify the failure class without containing user/model data.
        if (exception is TranscriptEnhancementException)
        {
            details.Add($"reason={exception.Message.Replace('\r', ' ').Replace('\n', ' ')}");
        }

        if (exception is HttpRequestException requestException && requestException.StatusCode is { } httpStatus)
        {
            details.Add($"httpStatus={(int)httpStatus}");
        }

        if (exception is SocketException socketException)
        {
            details.Add($"socketError={socketException.SocketErrorCode}");
        }

        if (exception is JsonException jsonException)
        {
            details.Add($"jsonPath={jsonException.Path ?? "unknown"}");
            details.Add($"jsonLine={jsonException.LineNumber?.ToString() ?? "unknown"}");
            details.Add($"jsonByte={jsonException.BytePositionInLine?.ToString() ?? "unknown"}");
        }

        if (exception is not HttpRequestException)
        {
            var status = TryReadNumericStatus(exception);
            if (status is not null)
            {
                details.Add($"httpStatus={status}");
            }
        }

        return string.Join(" ", details);
    }

    private static int? TryReadNumericStatus(Exception exception)
    {
        try
        {
            var property = exception.GetType().GetProperty(
                "Status",
                BindingFlags.Instance | BindingFlags.Public);
            var value = property?.GetValue(exception);
            return value switch
            {
                int status => status,
                Enum status => Convert.ToInt32(status),
                _ => null
            };
        }
        catch (Exception reflectionException) when (
            reflectionException is TargetInvocationException or MethodAccessException or InvalidOperationException)
        {
            return null;
        }
    }

    public void Dispose()
    {
        try
        {
            writer?.Dispose();
        }
        catch (IOException exception)
        {
            Console.Error.WriteLine(
                $"[WhisperDrop.AI] Could not finalize diagnostic file: {exception.GetType().Name}");
        }
    }

    private sealed class OperationScope(Action restore) : IDisposable
    {
        private Action? restore = restore;

        public void Dispose() => Interlocked.Exchange(ref restore, null)?.Invoke();
    }
}
